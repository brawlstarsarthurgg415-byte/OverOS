#!/usr/bin/env bash
set -Eeuo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)"
OVERLAY="${OVEROS_OVERLAY:?Set OVEROS_OVERLAY to the Buildroot rootfs overlay}"
OUTPUT="${OVERVAULT_OUTPUT:-$ROOT/out/overvault/x86_64}"
PKGNAME=fastfetch
PKGVER=2.53.0-1
ARCH=x86_64
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

command -v tar >/dev/null 2>&1 || { echo "tar is required" >&2; exit 1; }
command -v zstd >/dev/null 2>&1 || { echo "zstd is required" >&2; exit 1; }

install -D -m 0755 "$OVERLAY/usr/bin/fastfetch" "$STAGE/usr/bin/fastfetch"

if [ -f "$OVERLAY/etc/fastfetch/config.jsonc" ]; then
  install -D -m 0644 "$OVERLAY/etc/fastfetch/config.jsonc" "$STAGE/etc/fastfetch/config.jsonc"
fi
if [ -f "$OVERLAY/usr/share/fastfetch/logos/overos.txt" ]; then
  install -D -m 0644 "$OVERLAY/usr/share/fastfetch/logos/overos.txt" "$STAGE/usr/share/fastfetch/logos/overos.txt"
fi

SIZE="$(du -sk "$STAGE" | awk '{print $1 * 1024}')"
cat > "$STAGE/.PKGINFO" <<EOF
# Generated by OverVault
pkgname = $PKGNAME
pkgbase = $PKGNAME
pkgver = $PKGVER
pkgdesc = System information tool with OverOS branding
url = https://github.com/fastfetch-cli/fastfetch
builddate = $(date +%s)
packager = OverOS Project
size = $SIZE
arch = $ARCH
license = MIT
EOF

mkdir -p "$OUTPUT"
PACKAGE="$OUTPUT/$PKGNAME-$PKGVER-$ARCH.pkg.tar.zst"
tar --zstd -C "$STAGE" -cf "$PACKAGE" .PKGINFO usr etc
test -s "$PACKAGE"
echo "Created OverVault package: $PACKAGE"
